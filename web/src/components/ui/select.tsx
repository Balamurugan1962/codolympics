/**
 * The shape a filter or a short enum actually needs: a value, a change handler
 * and a list. Radix's Select is six components deep, which is right for a
 * country picker and wrong for "show: all / sold / unsold" repeated in nine
 * toolbars.
 */
function SimpleSelect<T extends string>({
  value,
  onValueChange,
  options,
  placeholder,
  className,
  size = "sm",
  disabled,
  "aria-label": ariaLabel,
}: {
  value: T;
  onValueChange: (v: T) => void;
  options: readonly { value: T; label: React.ReactNode; hint?: string }[];
  placeholder?: string;
  className?: string;
  size?: "sm" | "default";
  disabled?: boolean;
  "aria-label"?: string;
}) {
  return (
    <Select value={value} onValueChange={(v) => onValueChange(v as T)} disabled={disabled}>
      <SelectTrigger size={size} className={className} aria-label={ariaLabel}>
        <SelectValue placeholder={placeholder} />
      </SelectTrigger>
      <SelectContent>
        {options.map((o) => (
          <SelectItem key={o.value} value={o.value}>
            {o.label}
            {o.hint && <span className="ml-1 text-faint">{o.hint}</span>}
          </SelectItem>
        ))}
      </SelectContent>
    </Select>
  );
}

export { SimpleSelect };
